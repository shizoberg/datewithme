export const AvatarDisplay = ({ avatarId, size = 64 }: { avatarId: string; size?: number }) => {
  const avatar = avatars.find(a => a.id === avatarId)
  if (!avatar) {
    return (
      <div style={{
        width: size, height: size, borderRadius: '50%',
        background: '#00F680', display: 'flex',
        alignItems: 'center', justifyContent: 'center',
        fontFamily: 'Syne, sans-serif', fontWeight: 800,
        fontSize: size * 0.4, color: '#0D0D0D',
        flexShrink: 0,
      }}>?</div>
    )
  }
  return (
    <div
      style={{ width: size, height: size, borderRadius: '50%', overflow: 'hidden', flexShrink: 0, display: 'block' }}
      dangerouslySetInnerHTML={{ __html: avatar.svg }}
    />
  )
}
